/** One icon vocabulary: the 24dp, 1.5-stroke glyphs generated by design/build_assets.py. */
@Composable
fun Glyph(
    @DrawableRes id: Int,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
    contentDescription: String? = null,
) {
    Icon(painterResource(id), contentDescription, modifier.size(size), tint)
}

/** Subtle press feedback (scale 0.97, 120ms ease-out) for anything tappable. */
@Composable
fun Modifier.pressScale(source: MutableInteractionSource, pressed: Float = 0.97f): Modifier {
    val isPressed by source.collectIsPressedAsState()
    val scale by animateFloatAsState(
        targetValue = if (isPressed) pressed else 1f,
        animationSpec = tween(Motion.Fast, easing = Motion.EaseOut),
        label = "press",
    )
    return this.graphicsLayer { scaleX = scale; scaleY = scale }
}

private val ButtonShape = RoundedCornerShape(12.dp)
private val ButtonPadding = PaddingValues(horizontal = 22.dp)
private val ButtonMinHeight = 52.dp // comfortably above the 48dp touch minimum

@Composable
private fun RowScope.ButtonBody(text: String, @DrawableRes icon: Int?, loading: Boolean) {
    if (loading) {
        CircularProgressIndicator(Modifier.size(18.dp), color = LocalContentColor.current, strokeWidth = 2.dp)
        Spacer(Modifier.size(10.dp))
    } else if (icon != null) {
        Glyph(icon, size = 20.dp)
        Spacer(Modifier.size(8.dp))
    }
    Text(text, style = MaterialTheme.typography.labelLarge)
}

@Composable
fun PrimaryButton(
    text: String, onClick: () -> Unit, modifier: Modifier = Modifier,
    enabled: Boolean = true, loading: Boolean = false, @DrawableRes icon: Int? = null,
) {
    val source = remember { MutableInteractionSource() }
    Button(
        onClick = onClick, enabled = enabled && !loading, shape = ButtonShape, contentPadding = ButtonPadding,
        interactionSource = source, modifier = modifier.defaultMinSize(minHeight = ButtonMinHeight).pressScale(source),
    ) { ButtonBody(text, icon, loading) }
}

@Composable
fun SecondaryButton(
    text: String, onClick: () -> Unit, modifier: Modifier = Modifier,
    enabled: Boolean = true, @DrawableRes icon: Int? = null,
) {
    val source = remember { MutableInteractionSource() }
    OutlinedButton(
        onClick = onClick, enabled = enabled, shape = ButtonShape, contentPadding = ButtonPadding,
        border = BorderStroke(1.dp, MaterialTheme.colorScheme.outline), interactionSource = source,
        colors = ButtonDefaults.outlinedButtonColors(contentColor = MaterialTheme.colorScheme.onSurface),
        modifier = modifier.defaultMinSize(minHeight = ButtonMinHeight).pressScale(source),
    ) { ButtonBody(text, icon, false) }
}

@Composable
fun TonalButton(
    text: String, onClick: () -> Unit, modifier: Modifier = Modifier,
    enabled: Boolean = true, @DrawableRes icon: Int? = null,
) {
    val source = remember { MutableInteractionSource() }
    FilledTonalButton(
        onClick = onClick, enabled = enabled, shape = ButtonShape, contentPadding = ButtonPadding, interactionSource = source,
        colors = ButtonDefaults.filledTonalButtonColors(
            containerColor = MaterialTheme.colorScheme.primaryContainer, contentColor = MaterialTheme.colorScheme.primary,
        ),
        modifier = modifier.defaultMinSize(minHeight = ButtonMinHeight).pressScale(source),
    ) { ButtonBody(text, icon, false) }
}

@Composable
fun QuietButton(text: String, onClick: () -> Unit, modifier: Modifier = Modifier, @DrawableRes icon: Int? = null) {
    TextButton(onClick = onClick, shape = ButtonShape, modifier = modifier.defaultMinSize(minHeight = 48.dp)) {
        ButtonBody(text, icon, false)
    }
}

enum class ChipKind { Present, Review, Absent, Neutral }

/** Status is never colour alone: every chip carries a word. */
@Composable
fun StatusChip(text: String, kind: ChipKind, modifier: Modifier = Modifier) {
    val cs = MaterialTheme.colorScheme
    val (bg, fg) = when (kind) {
        ChipKind.Present -> cs.primaryContainer to cs.primary
        ChipKind.Review -> cs.tertiaryContainer to cs.tertiary
        ChipKind.Absent -> cs.errorContainer to cs.error
        ChipKind.Neutral -> cs.surfaceContainer to cs.secondary
    }
    Row(
        modifier.height(24.dp).clip(RoundedCornerShape(6.dp)).background(bg).padding(horizontal = 8.dp),
        verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp),
    ) {
        Box(Modifier.size(6.dp).background(fg, CircleShape))
        Text(text, color = fg, style = MaterialTheme.typography.labelMedium, maxLines = 1)
    }
}

/** Screen title with an optional subtitle and trailing actions. */
@Composable
fun ScreenHeader(title: String, subtitle: String? = null, trailing: @Composable RowScope.() -> Unit = {}) {
    Row(
        Modifier.fillMaxWidth().padding(start = 20.dp, end = 8.dp, top = 8.dp, bottom = 8.dp).defaultMinSize(minHeight = 56.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(Modifier.weight(1f)) {
            Text(title, style = MaterialTheme.typography.headlineMedium, color = MaterialTheme.colorScheme.onSurface)
            if (subtitle != null) {
                Text(subtitle, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
        }
        trailing()
    }
}

@Composable
fun GroupHeader(label: String, count: Int? = null) {
    Row(
        Modifier.fillMaxWidth().padding(start = 20.dp, end = 20.dp, top = 20.dp, bottom = 8.dp),
        horizontalArrangement = Arrangement.SpaceBetween, verticalAlignment = Alignment.CenterVertically,
    ) {
        Text(label, style = MaterialTheme.typography.titleSmall, color = MaterialTheme.colorScheme.secondary)
        if (count != null) Text(count.toString(), style = MonoLabel, color = MaterialTheme.colorScheme.onSurfaceVariant)
    }
}

/** Hairline-bounded list surface. Rows inside separate themselves with [Hairline]. */
@Composable
fun ListSurface(content: @Composable () -> Unit) {
    Column(Modifier.fillMaxWidth().background(MaterialTheme.colorScheme.surfaceContainerLowest)) {
        Hairline()
        content()
        Hairline()
    }
}

@Composable
fun Hairline(modifier: Modifier = Modifier) {
    HorizontalDivider(modifier, thickness = 1.dp, color = MaterialTheme.colorScheme.outlineVariant)
}

@Composable
fun EmptyState(@DrawableRes icon: Int, title: String, body: String, modifier: Modifier = Modifier) {
    Column(modifier.fillMaxWidth().padding(horizontal = 28.dp, vertical = 56.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
        Glyph(icon, size = 28.dp, tint = MaterialTheme.colorScheme.onSurfaceVariant)
        Text(title, style = MaterialTheme.typography.titleMedium)
        Text(body, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
    }
}
